SELECT * FROM gold_fact_sales;

-- 1) DATABASE EXPLORATION--
-- EXPLORE ALL OBJECRS IN DATABASE-- 
SELECT * FROM INFORMATION_SCHEMA.TABLES;

-- 2) dimensions exploration--
-- EXPLORE ALL COLUMNS IN DATABASE -- 
SELECT * FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_NAME = 'gold_dim_customers';

-- task-1 = explore all countries our customer come from --
SELECT DISTINCT country from gold_dim_customers; 

-- exlpore all product categories "the major divisions"-- 
SELECT DISTINCT category,subcategory,product_name FROM gold_dim_products;

-- 3) date exploration--
-- find date of first and last order--
SELECT MIN(order_date),
MAX(order_date),
DATEDIFF(month,MIN(order_date),MAX(order_date)) AS order_range_years
FROM gold_fact_sales;

-- find youngest and oldest customer
SELECT MIN(birthdate) AS Old_cust ,
MAX(birthdate) AS young_cust ,
DATEDIFF(year,MIN(birthdate) , GETDATE()) AS old_age,
DATEDIFF(year,MAX(birthdate) , GETDATE()) AS young_age
FROM gold.dim_customers;

-- 4) MEASURES EXPLORATION
SELECT SUM(sales_amount) AS TOTAL_SALES,
SUM(quantity) as total_quantity,
AVG(price) as avg_Price,
COUNT(order_number) as total_orders,
COUNT(DISTINCT order_number) as total_orders1,
COUNT(customer_key) as total_customers,
COUNT(DISTINCT customer_key) as total_customers1
FROM gold_fact_sales;


-- generate reports that show all key bussiness metrics 
SELECT 'TOTAL_SALES' as measure_name , sum(sales_amount) as measure_value FROM gold_fact_sales
UNION ALL
SELECT 'TOTAL_QUANTITY' as measure_name , sum(quantity) as measure_value FROM gold_fact_sales
UNION ALL
SELECT 'TOTAL_ORDERS' as measure_name , sum(order_number) as measure_value FROM gold_fact_sales;

-- 5)MAGNITUDE ANALYSIS
-- select total customers from country
SELECT country , COUNT(customer_key) AS total_customers FROM gold.dim_customers
GROUP BY country
ORDER BY total_customers DESC;

-- find total customers by gender
SELECT gender , COUNT(customer_key) as tot_cust FROM gold.dim_customers
GROUP BY gender
ORDER BY total_customers DESC;

-- find total products by category
SELECT COUNT(product_key) as total_products , category from gold.dim_products
GROUP BY category
ORDER BY total_products DESC;

-- what is average costs in each category
SELECT AVG(cost) as avg_costs, category from gold.dim_products
GROUP BY category
ORDER BY avg_costs DESC;

-- what is total revenue generated by each category 
SELECT p.category , SUM(f.sales_amount) total_revenue FROM gold_fact_sales f 
LEFT JOIN gold.dim_products p 
ON f.product_key = p.product_key
GROUP BY p.category
ORDER BY total_revenue DESC;

-- 6) RANKING ANALYSIS
-- which 5 products generate the highest revenue
SELECT TOP 5
p.product_name , 
SUM(f.sales_amount) total_revenue 
FROM gold_fact_sales f 
LEFT JOIN gold.dim_products p 
ON p.product_key = f.product_key
GROUP BY p.product_name
ORDER BY total_revenue DESC






